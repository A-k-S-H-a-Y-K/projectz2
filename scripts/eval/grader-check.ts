// Checks the answer grader itself. If every answer passes the answer evaluation, that only
// means something if the grader can catch mistakes, so this gives it answers with known,
// deliberately planted mistakes (and some correct ones) and reports what it caught.
// Run with: npm run eval:grader
//
// Needs no database or search: the notes come straight from the dataset. One chat call per case.
import { writeFile } from 'node:fs/promises';
import { memories } from './dataset.js';
import { grade, GRADER_MODEL, type Grade, type GradedNote } from './grader.js';
import { sleep, withRetry } from '../lib/load-memories.js';

const CHAT_PAUSE_MS = 5000;

const note = (key: string): GradedNote => {
  const memory = memories.find((m) => m.key === key);
  if (!memory) throw new Error(`No memory with key ${key}`);
  return { title: memory.title, content: memory.content, createdAt: new Date(memory.savedAt) };
};

type Check = keyof Pick<Grade, 'unsupportedClaims' | 'wrongCitations' | 'timingErrors'>;

interface Case {
  mistake: string;
  question: string;
  notes: string[];
  answer: string;
  // The check that should flag the planted mistake, or null for a correct answer
  shouldFlag: Check | null;
}

const cases: Case[] = [
  {
    mistake: 'Wrong number (the note says 4,200 rupees)',
    question: 'How much did my travel insurance cost?',
    notes: ['europe-trip'],
    answer: 'Your travel insurance cost 5,200 rupees [1].',
    shouldFlag: 'unsupportedClaims',
  },
  {
    mistake: 'Invented name (the mentor is Priya)',
    question: 'Who is guiding me at my internship?',
    notes: ['internship'],
    answer: 'Your mentor at Zentrix Labs is Rahul [1].',
    shouldFlag: 'unsupportedClaims',
  },
  {
    mistake: 'Guessed personal fact (only Mom\'s birthday is saved)',
    question: "When is my dad's birthday?",
    notes: ['mom-birthday'],
    answer: "Your dad's birthday is on 14 August [1].",
    shouldFlag: 'unsupportedClaims',
  },
  {
    mistake: 'Citation points to the wrong note (scuba is in note 1, not 2)',
    question: 'Where did I try scuba diving?',
    notes: ['goa-trip', 'manali-trip'],
    answer: 'You tried scuba diving at Grande Island [2].',
    shouldFlag: 'wrongCitations',
  },
  {
    mistake: 'Citation on a "not in your notes" sentence',
    question: 'What medicine does my mother take?',
    notes: ['dad-medicine'],
    answer: "Your mother's medicine isn't in your notes [1].",
    shouldFlag: 'wrongCitations',
  },
  {
    mistake: 'Past trip called upcoming (June 2026 has passed)',
    question: 'What trips do I have coming up?',
    notes: ['europe-trip'],
    answer: 'You have an upcoming Europe trip with Arjun from 4 to 18 June 2026 [1].',
    shouldFlag: 'timingErrors',
  },
  {
    mistake: 'None (correct answer)',
    question: 'Where did I try scuba diving?',
    notes: ['goa-trip'],
    answer: 'You tried scuba diving at Grande Island on your Goa trip [1].',
    shouldFlag: null,
  },
  {
    mistake: 'None (correct refusal)',
    question: "When is my dad's birthday?",
    notes: ['mom-birthday'],
    answer: "Your dad's birthday isn't in your notes.",
    shouldFlag: null,
  },
  {
    mistake: 'None (past plan described correctly)',
    question: 'What trips do I have coming up?',
    notes: ['europe-trip'],
    answer:
      "Your notes don't mention any upcoming trips. You had a Europe trip with Arjun planned for 4 to 18 June 2026 [1], and your notes don't say whether it happened.",
    shouldFlag: null,
  },
];

const problemCount = (g: Grade) =>
  g.unsupportedClaims.length + g.wrongCitations.length + g.timingErrors.length;

const lines = [
  '# Grader check',
  '',
  `Run on ${new Date().toISOString().slice(0, 10)} with ${GRADER_MODEL}. ` +
    'Generated by `npm run eval:grader`.',
  '',
  '| Planted mistake | Expected | Grader found | Result |',
  '|---|---|---|---|',
];

let caught = 0;
let falseAlarms = 0;
const planted = cases.filter((c) => c.shouldFlag !== null).length;

for (const [i, c] of cases.entries()) {
  console.log(`[${i + 1}/${cases.length}] ${c.mistake}`);
  const g = await withRetry(() => grade(c.question, c.notes.map(note), c.answer), 'grading');

  const found = (['unsupportedClaims', 'wrongCitations', 'timingErrors'] as const)
    .filter((check) => g[check].length > 0)
    .map((check) => `${check}: ${g[check].join('; ')}`);

  let result: string;
  if (c.shouldFlag === null) {
    const ok = problemCount(g) === 0;
    if (!ok) falseAlarms += 1;
    result = ok ? '✅ no false alarm' : '❌ false alarm';
  } else {
    // It counts as caught if any check flags it, but the expected check is noted
    const ok = problemCount(g) > 0;
    if (ok) caught += 1;
    result = !ok ? '❌ missed' : g[c.shouldFlag].length > 0 ? '✅ caught' : '✅ caught (other check)';
  }

  lines.push(
    `| ${c.mistake} | ${c.shouldFlag ?? 'nothing'} | ${found.join('<br>').replace(/\|/g, '/') || 'nothing'} | ${result} |`
  );
  await sleep(CHAT_PAUSE_MS);
}

const correctCases = cases.length - planted;
lines.splice(
  4,
  0,
  `**Caught ${caught} of ${planted} planted mistakes, with ${falseAlarms} false alarms on ` +
    `${correctCases} correct answers.**`,
  ''
);

const report = lines.join('\n') + '\n';
await writeFile(new URL('./grader-check.md', import.meta.url), report);
console.log(`\n${report}`);
console.log('Saved to scripts/eval/grader-check.md');
process.exit(0);
